# Creamos una lista con 5 frutas.
frutas = ["manzana", "platano", "naranja", "ciruela", "fresa"]

# Muestra la primera y la última fruta.
print(frutas[0])
print(frutas[-1])

# Cambio el kiwi por el plátano.
